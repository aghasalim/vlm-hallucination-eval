"""Hand-verified ground truth. This file is the evaluation set.

Every entry below was produced by looking at the actual image (contact sheets in
data/sheets/, generated by contact_sheets.py) and deciding, per probe, whether
the object is genuinely absent. Probes I could not confirm were dropped rather
than guessed, that is why some images contribute two probes and others five.

Three rules I applied, and the reasoning:

1. **Absence must be visually certain, not merely unannotated.** COCO labels 80
   categories and misses instances even within them, so "not in the annotations"
   is not evidence of absence. Cluttered indoor scenes were the worst offenders:
   in a kitchen a fork is *plausible everywhere*, so I dropped cutlery probes for
   kitchens even though COCO listed none.

2. **Adversarial means confusable, not merely absent.** Asking whether a ski
   slope contains a toothbrush measures nothing; asking whether it contains a
   *skateboard* probes whether the model distinguishes board sports. Probes are
   labelled by kind so the three POPE splits can be reported separately.

3. **Ambiguous categories were dropped entirely.** The playroom image (371699)
   would have been a lovely "bear" probe against a dog, but COCO separates "bear"
   from "teddy bear" and a toy would make a "yes" defensible. An eval item whose
   correct answer is arguable is worse than no eval item.

The honest cost of rule 1: this set is biased toward outdoor and single-subject
scenes, because those are the ones where absence is verifiable. Hallucination
rates measured here may therefore be *optimistic* relative to the cluttered
indoor scenes that are hardest for VLMs, I could not certify ground truth on
exactly the images the model would most likely fail. That limitation is real and
is repeated in the README.
"""
