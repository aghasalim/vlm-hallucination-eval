def build() -> list[dict]:
    draft = {r["file_name"].replace(".jpg", ""): r
             for r in json.loads((config.DATA / "eval_set_draft.json").read_text())}
    out = []
    for stem, (scene, why, absent) in VERIFIED.items():
        r = draft[stem]
        # A verified-absent object must not also be listed present: that would
        # be a contradiction between my eyes and the annotations, and I would
        # rather the build fail than ship it.
        clash = set(absent) & set(r["present"])
        if clash:
            raise ValueError(f"{stem}: marked absent but COCO lists present: {clash}")
        out.append({
            "image_id": r["image_id"],
            "file_name": r["file_name"],
            "scene": scene,
            "why_hard": why,
            "n_instances": r["n_instances"],
            "present": r["present"],
            "absent": absent,
        })
    return out


def main() -> None:
    rows = build()
    config.EVAL_SET.write_text(json.dumps(rows, indent=2))
    n_pos = sum(len(r["present"]) for r in rows)
    kinds: dict[str, int] = {}
    for r in rows:
        for k in r["absent"].values():
            kinds[k] = kinds.get(k, 0) + 1
    print(f"{len(rows)} images -> {config.EVAL_SET}")
    print(f"  {n_pos} positive probes (objects COCO annotates as present)")
    print(f"  {sum(kinds.values())} verified-absent probes by kind: {kinds}")
    print(f"  mean instances per image: {sum(r['n_instances'] for r in rows) / len(rows):.1f}")


if __name__ == "__main__":
    main()
